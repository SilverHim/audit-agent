"""生成独立精简合成演示: 两份合同、一项截止异常、一项分录复核和一份银行回函.

原 Numbat 与 Xero 目录只读. 所有新金额与交易均为合成, 不从真实联系人或 Posted By 取数.
"""

import csv
import hashlib
import json
import shutil
from pathlib import Path

from reportlab.pdfgen.canvas import Canvas

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "demo-compact"
NOTICE = "Synthetic - for demonstration only"
FIXTURES = ROOT.parent / "tests/fixtures/llm_compact"


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def write_csv(name: str, rows: list[dict], fields: list[str] | None = None) -> None:
    with (OUT / f"{name}.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields or list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def pdf(path: str, title: str, lines: list[str]) -> str:
    target = OUT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    canvas = Canvas(str(target), invariant=1)
    canvas.setTitle(title)
    canvas.setFont("Helvetica", 10)
    for index, line in enumerate([NOTICE, title, "", *lines]):
        canvas.drawString(40, 800 - index * 17, line)
    canvas.save()
    return "DOC-" + hashlib.sha256(target.read_bytes()).hexdigest()[:12]


def generate() -> None:
    # 拒绝生成目录或已存在文件通过链接覆盖目录外资料.
    if any(parent.is_symlink() for parent in [OUT, *OUT.parents]) or any(
        p.is_symlink() or (p.is_file() and p.stat().st_nlink > 1) for p in OUT.rglob("*")
    ):
        raise ValueError("精简演示生成目录含链接")
    OUT.mkdir(parents=True, exist_ok=True)
    # 共享同一合成公司的客户画像与公开登记 mock; 内容逐字保留, 同客户的项目之间不制造不同画像.
    shutil.copyfile(ROOT / "demo/client_profile.json", OUT / "client_profile.json")
    for name in ("abn.json", "asic.json"):
        target = OUT / "registry" / name
        target.parent.mkdir(exist_ok=True)
        shutil.copyfile(ROOT / "demo/registry" / name, target)
    (OUT / "README.md").write_text(
        f"# {NOTICE}\n\nCompact Numbat demonstration, FY ended 30 June 2026. "
        "Two revenue contracts; one cut-off exception; "
        "one journal approval exception; one bank interest difference. "
        "Generated by data/generate_compact_demo.py. Original datasets are unchanged.\n"
    )
    account_defs = [
        ("100", "Cash at bank", "asset", "cash"),
        ("120", "Trade receivables", "asset", "receivables"),
        ("300", "Share capital", "equity", "share_capital"),
        ("310", "Retained earnings", "equity", "retained_earnings"),
        ("400", "Sales revenue", "revenue", "revenue"),
        ("410", "Interest income", "revenue", "other_income"),
        ("500", "Operating expenses", "expense", "operating_expenses"),
    ]
    write_csv("accounts", [dict(code=c, name=n, type=t, category=k) for c, n, t, k in account_defs])
    transactions = [
        ("CJ-001", "2026-06-10", "120", "400", 3456789, "INV-C01", "Goods sold and accepted"),
        ("CJ-002", "2026-06-29", "120", "400", 1234567, "INV-C02", "Goods invoiced before customer acceptance"),
        ("CJ-003", "2026-05-19", "500", "100", 765432, "EXP-C01", "Operating costs"),
        ("CJ-004", "2026-06-12", "100", "120", 3456789, "INV-C01", "Customer receipt"),
        ("CJ-005", "2026-06-18", "500", "100", 55555, "EXP-C02", "Approved administration expense"),
    ]
    journals = []
    approvals = []
    for no, day, debit, credit, amount, source, desc in transactions:
        maker = "staff-a" if no != "CJ-005" else "director-a"
        approver = "manager-b" if no != "CJ-005" else "director-a"
        approvals.append(dict(entry_no=no, created_by=maker, approved_by=approver, approved_at=f"{day}T06:00:00Z"))
        for index, (code, dr, cr) in enumerate([(debit, amount, 0), (credit, 0, amount)], 1):
            journals.append(
                dict(
                    id=f"{no}-{index}",
                    entry_no=no,
                    posting_date=day,
                    created_at=f"{day}T05:00:00Z",
                    created_by=maker,
                    approved_by=approver,
                    approved_at=f"{day}T06:00:00Z",
                    account_code=code,
                    debit_cents=dr,
                    credit_cents=cr,
                    description=desc,
                    source_doc=source,
                    is_adjustment=False,
                )
            )
    write_csv("journal_entries", journals)
    write_csv("approval_log", approvals)
    prior = {"100": 10000000, "300": -7000000, "310": 0, "400": -4000000, "500": 1000000}
    current = {c: 0 for c, *_ in account_defs}
    current.update({"100": 10000000, "300": -7000000, "310": -3000000})
    for line in journals:
        current[line["account_code"]] += line["debit_cents"] - line["credit_cents"]
    assert sum(prior.values()) == sum(current.values()) == 0
    write_csv(
        "trial_balance",
        [
            dict(period=p, account_code=c, balance_cents=balances.get(c, 0))
            for p, balances in [("prior", prior), ("current", current)]
            for c, *_ in account_defs
        ],
    )
    write_csv(
        "sales_invoices",
        [
            dict(
                id=f"SI-C0{i}",
                invoice_no=f"INV-C0{i}",
                customer=f"Synthetic Customer {i}",
                customer_abn=None,
                contract_id=f"CON-C0{i}",
                invoice_date=day,
                posting_date=day,
                amount_cents=amount,
                journal_entry_id=f"CJ-00{i}-2",
            )
            for i, day, amount in [(1, "2026-06-10", 3456789), (2, "2026-06-29", 1234567)]
        ],
    )
    write_csv(
        "delivery_notes",
        [
            dict(
                id=f"DN-C0{i}",
                delivery_no=f"DN-C0{i}",
                invoice_id=f"SI-C0{i}",
                shipped_date=day,
                signed_date=day,
                signed_by=f"Synthetic receiver {i}",
            )
            for i, day in [(1, "2026-06-10"), (2, "2026-07-03")]
        ],
    )
    write_csv(
        "supplier_bills",
        [],
        ["id", "bill_no", "supplier", "bill_date", "due_date", "amount_cents", "outstanding_cents", "journal_entry_id"],
    )
    write_csv(
        "bank_accounts",
        [
            dict(
                id="BA-C01",
                bank_name="Synthetic Demonstration Bank",
                bsb="000000",
                account_no="88000101",
                gl_account_code="100",
            )
        ],
    )
    balance = 10000000
    movements = []
    for i, (day, amount, ref) in enumerate(
        [("2026-05-19", -765432, "EXP-C01"), ("2026-06-12", 3456789, "INV-C01"), ("2026-06-18", -55555, "EXP-C02")], 1
    ):
        balance += amount
        movements.append(
            dict(
                id=f"BT-C0{i}",
                bank_account_id="BA-C01",
                txn_date=day,
                amount_cents=amount,
                balance_after_cents=balance,
                description="Synthetic bank movement",
                reference=ref,
            )
        )
    assert balance == current["100"]
    write_csv("bank_transactions", movements)
    documents = []

    def document(path: str, title: str, lines: list[str], stage: str, kind: str, related: list[str]) -> None:
        did = pdf(path, title, lines)
        documents.append(
            dict(
                path=path,
                file_name=Path(path).name,
                stage=stage,
                document_type=kind,
                reliability="external_copy" if kind == "contract" else "internal_original",
                document_date="2026-06-30",
                related_ids=related,
                document_id=did,
            )
        )

    company = "Numbat Electronic Components Pty Ltd"
    document(
        "acceptance/appointment.pdf",
        "Shareholder resolution appointing auditor",
        [
            company,
            "Resolution dated 1 July 2025: appoint a registered company auditor for FY ended 30 June 2026.",
            "Authorised by all shareholders. No limitation of scope or access to records.",
        ],
        "acceptance",
        "minutes",
        [],
    )
    document(
        "acceptance/engagement_letter.pdf",
        "Audit engagement letter",
        [
            company,
            "Signed 1 July 2025 by the directors and auditor.",
            "Audit of the financial report for 1 July 2025 to 30 June 2026 under Australian Auditing Standards.",
            "Management accepts responsibility for preparing the report under Australian Accounting Standards,",
            "internal control, and unrestricted access to records, information and persons.",
            "The auditor will express an independent opinion. The report may be modified where required.",
            "No restrictions on audit procedures, access or communication with those charged with governance.",
        ],
        "acceptance",
        "engagement_letter",
        [],
    )
    for i, amount, delivered in [(1, "34,567.89", "10 June 2026"), (2, "12,345.67", "3 July 2026")]:
        document(
            f"contracts/CON-C0{i}.pdf",
            f"CON-C0{i}: goods supply agreement",
            [
                f"Supplier: {company}",
                f"Customer: Synthetic Customer {i}",
                "Signed: 1 May 2026. Currency: AUD. All amounts exclude GST; this synthetic transaction has no GST.",
                f"Fixed transaction price: AUD {amount}. Invoice: INV-C0{i}.",
                "One performance obligation: delivery of electronic components. No services, rebates or financing.",
                "Control transfers only upon physical delivery and signed customer acceptance.",
                "No bill-and-hold arrangement; no over-time revenue recognition; no returns or variable consideration.",
                f"Delivery and signed acceptance: {delivered}. Payment is due 30 days after acceptance.",
            ],
            "fieldwork",
            "contract",
            [f"CON-C0{i}", f"SI-C0{i}"],
        )
    document(
        "support/expense.pdf",
        "Expense invoice and approval record",
        [
            company,
            "CJ-005 / EXP-C02: administration services, AUD 555.55, supplied and paid 18 June 2026.",
            ("Recorded and approved by director-a. This is a genuine business cost supported by the attached invoice."),
            "The same-person approval is an internal control exception; it is not evidence of an amount error.",
            "CJ-003 / EXP-C01: operating costs AUD 7,654.32, supplied and paid 19 May 2026.",
            "Recorded by staff-a and independently approved by manager-b.",
        ],
        "fieldwork",
        "internal_record",
        ["CJ-003", "CJ-005"],
    )
    document(
        "support/representation_letter.pdf",
        "Management representation letter",
        [
            company,
            "Signed by the directors for the audit of FY ended 30 June 2026.",
            (
                "Management confirms responsibility for the financial report, internal control an"
                "d complete access to records."
            ),
            (
                "All transactions and related parties have been disclosed. No unrecorded litigati"
                "on, fraud or subsequent events."
            ),
            "All proposed audit corrections will be evaluated and communicated in the management response record.",
        ],
        "manual",
        "representation_letter",
        [],
    )
    document(
        "support/management_response.pdf",
        "Management response to proposed audit adjustments",
        [
            company,
            "Synthetic management communication dated 20 July 2026, acknowledged by the directors.",
            "SI-C02: goods accepted on 3 July 2026; reverse FY2026 revenue and receivables AUD 12,345.67.",
            "BA-C01: recognise accrued interest receivable and interest income AUD 355.55 at 30 June 2026.",
            "Management agrees to both corrections. Entries AJE-C01 and AJE-C02 were posted on 20 July 2026.",
            "These corrections address all proposed amount errors in this compact synthetic demonstration.",
        ],
        "manual",
        "internal_record",
        ["SI-C02", "BA-C01"],
    )
    pdf(
        "confirmations/88000101.pdf",
        "Direct bank confirmation",
        [
            company,
            "Account 88000101; BSB 000000; currency AUD; balance date 30 June 2026.",
            f"Confirmed deposited balance: AUD {balance / 100:,.2f}.",
            (
                "Accrued interest owing to the customer at 30 June 2026: AUD 355.55, not included"
                " in the confirmed balance."
            ),
            "No loans, guarantees, security interests, restrictions or other facilities.",
            "Sent directly to the auditor by Synthetic Demonstration Bank.",
        ],
    )
    write_json(OUT / "confirmations/receipts.json", {"88000101": {"receipt_channel": "direct_email"}})
    for filename in ("audit_objectives.json", "risk_register.json"):
        value = json.loads((ROOT / "demo/planning" / filename).read_text())
        if filename == "risk_register.json":
            for risk in value:
                risk["description"] = (
                    "Synthetic compact audit: evaluate revenue recognition and period-end delivery, and confirm cash."
                )
        write_json(OUT / "planning" / filename, value)
    corrections = []
    for no, dr, cr, amount, desc in [
        ("AJE-C01", "400", "120", 1234567, "Reverse revenue before customer acceptance"),
        ("AJE-C02", "120", "410", 35555, "Record accrued interest receivable"),
    ]:
        for i, (code, debit, credit) in enumerate([(dr, amount, 0), (cr, 0, amount)], 1):
            corrections.append(
                dict(
                    id=f"{no}-{i}",
                    entry_no=no,
                    posting_date="2026-06-30",
                    created_at="2026-07-20T06:00:00Z",
                    created_by="staff-a",
                    approved_by="manager-b",
                    approved_at="2026-07-20T07:00:00Z",
                    account_code=code,
                    debit_cents=debit,
                    credit_cents=credit,
                    description=desc,
                    source_doc="SI-C02" if no == "AJE-C01" else "BA-C01",
                    is_adjustment=True,
                )
            )
    (OUT / "adjustments").mkdir(exist_ok=True)
    with (OUT / "adjustments/journal_entries.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(corrections[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(corrections)
    if FIXTURES.is_dir():
        runtime = OUT / "llm"
        if runtime.exists():
            shutil.rmtree(runtime)
        shutil.copytree(FIXTURES, runtime)
    files = {
        p.relative_to(OUT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(OUT.rglob("*"))
        if p.is_file() and p.name != "compact.json"
    }
    write_json(
        OUT / "compact.json",
        dict(notice=NOTICE, period_start="2025-07-01", period_end="2026-06-30", documents=documents, files=files),
    )
    print(
        f"Generated compact synthetic demo: {len(journals)} journal rows, "
        f"2 contracts, {len(documents)} staged documents."
    )


if __name__ == "__main__":
    generate()
